"use strict";

const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const source = fs.readFileSync(
  path.join(__dirname, "../src/modules/billing/billing.controller.js"),
  "utf8"
);

function section(start, end) {
  const a = source.indexOf(start);
  const b = source.indexOf(end, a + start.length);

  assert.ok(a >= 0, `Missing function: ${start}`);
  assert.ok(b > a, `Missing next function: ${end}`);

  return source.slice(a, b);
}

const renewal = section(
  "async function initiateRenewalPayment(req, res) {",
  "async function devMarkRenewalPaymentSuccessful(req, res) {"
);

const status = section(
  "async function getRenewalPaymentStatus(req, res) {",
  "async function getBillingUsage(req, res) {"
);

test("1. Renewal references are generated by the server", () => {
  assert.match(
    renewal,
    /const reference = makeReference\("RENEW"\)/
  );
  assert.doesNotMatch(renewal, /externalReference/);
});

test("2. Renewal creates a new payment without upsert", () => {
  assert.match(renewal, /prisma\.payment\.create\(/);
  assert.doesNotMatch(renewal, /prisma\.payment\.upsert\(/);
});

test("3. Renewal records trusted payment values", () => {
  assert.match(renewal, /amount: snap\.price/);
  assert.match(
    renewal,
    /purpose: "SUBSCRIPTION_RENEWAL"/
  );
  assert.match(renewal, /status: "PENDING"/);
});

test("4. Payment status requires tenant ownership", () => {
  assert.match(status, /normalizeTenantId\(req\)/);
  assert.match(
    status,
    /payment\.tenantId !== tenantId/
  );
  assert.match(
    status,
    /payment\.purpose !== "SUBSCRIPTION_RENEWAL"/
  );
});
